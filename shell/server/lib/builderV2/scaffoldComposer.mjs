export function renderScaffoldFoundation(graph) {
  const protectedFiles = {
    [SCAFFOLD_ENTRY_PATH]: `${banner("application entry shim")}export { default } from "./lib/scaffolds/composed/ScaffoldApp.jsx";\n`,
    [SCAFFOLD_PRIMITIVES_PATH]: primitivesSource(),
    [SCAFFOLD_APP_PATH]: scaffoldAppSource(graph),
    [SCAFFOLD_MANIFEST_PATH]: manifestSource(graph),
  };
  const screenFiles = Object.fromEntries((graph?.screens || []).map((screen) => [screen.module,
    screenSlotSource(screen, graph)]));
  return { protectedFiles, screenFiles };
}

export function scaffoldCompositionPlan(graph) {
  const rendered = renderScaffoldFoundation(graph);
  const protectedFiles = Object.keys(rendered.protectedFiles).sort();
  return {
    version: SCAFFOLD_COMPOSITION_VERSION,
    graphVersion: graph?.version || 1,
    registryVersion: graph?.registryVersion || 1,
    protectedRoot: SCAFFOLD_COMPOSED_ROOT,
    protectedFiles,
    protectedFileHashes: Object.fromEntries(protectedFiles.map((path) => [path, digest(rendered.protectedFiles[path])])),
    modelOwnedScreenFiles: Object.keys(rendered.screenFiles).sort(),
    routeScreenMap: (graph?.routes || []).map((route) => ({ routePath: route.routePath,
      screenId: route.screenId, module: route.module, journeyIds: route.journeyIds || [] })),
    extensionPoints: (graph?.extensions || []).map((extension) => ({ ...extension })),
    familyInterfaces: (graph?.families || []).map((node) => ({ scaffoldId: node.scaffoldId,
      version: node.version, extensionPoints: scaffoldEntry(node.scaffoldId)?.extensionPoints || [] })),
    expectedModuleSurface: graph?.expectedModuleSurface || null,
  };
}

/** Apply/refresh deterministic files. Existing model-owned screens are never overwritten. */
export function composeScaffoldFoundation(tree, graph) {
  const rendered = renderScaffoldFoundation(graph);
  const next = { ...(tree || {}), ...rendered.protectedFiles };
  for (const [path, source] of Object.entries(rendered.screenFiles)) {
    if (typeof next[path] !== "string") next[path] = source;
  }
  return { tree: next, plan: scaffoldCompositionPlan(graph), deterministicFilesCreated: Object.keys(rendered.protectedFiles),
    screenSlotsCreated: Object.keys(rendered.screenFiles).filter((path) => typeof tree?.[path] !== "string") };
}

function hasExport(source, name) {
  if (name === "default") return /\bexport\s+default\b/.test(source);
  return new RegExp(`\\bexport\\s+(?:async\\s+)?(?:function|class|const|let|var)\\s+${name}\\b`).test(source)
    || new RegExp(`\\bexport\\s*\\{[^}]*\\b${name}\\b`).test(source);
}

function isUnimplementedScreenSlot(source, screenId) {
  // The provenance comment intentionally survives replace_symbol patches. Placeholder detection
  // must follow the live render body, otherwise a fully implemented mounted screen is rejected
  // merely because the model preserved that useful ownership comment.
  return source.includes(`data-scaffold-slot=${quote(screenId)}`)
    && source.includes("Application screen ready for composition.");
}

export function validateScaffoldComposition(tree, graph, plan = scaffoldCompositionPlan(graph), {
  requireExtensions = true, rejectScreenSlots = false, journeyIds = null,
} = {}) {
  const problems = [];
  const selectedJourneys = journeyIds ? new Set(journeyIds) : null;
  for (const path of plan.protectedFiles || []) {
    if (typeof tree?.[path] !== "string") { problems.push(`protected scaffold module missing: ${path}`); continue; }
    const expected = plan.protectedFileHashes?.[path];
    if (expected && digest(tree[path]) !== expected) problems.push(`protected scaffold module modified: ${path}`);
  }
  for (const route of plan.routeScreenMap || []) {
    const source = tree?.[route.module];
    if (typeof source !== "string") problems.push(`mounted scaffold screen missing: ${route.module}`);
    else if (!hasExport(source, "default")) problems.push(`mounted scaffold screen must default export: ${route.module}`);
    else if (rejectScreenSlots && (!selectedJourneys
      || (route.journeyIds || []).some((id) => selectedJourneys.has(id)))
      && isUnimplementedScreenSlot(source, route.screenId)) problems.push(`mounted scaffold screen is still unimplemented: ${route.module}`);
    const router = String(tree?.[SCAFFOLD_APP_PATH] || "");
    if (!router.includes(JSON.stringify(route.routePath)) || !router.includes(route.module.split("/").at(-1).replace(/\.(?:jsx?|tsx?)$/, ""))) {
      problems.push(`route ${route.routePath} does not mount ${route.module}`);
    }
  }
  for (const owner of graph?.journeyOwnership || []) {
    const route = (plan.routeScreenMap || []).find((candidate) => candidate.screenId === owner.screenId);
    if (!route || route.module !== owner.mountedModule || !route.journeyIds.includes(owner.journeyId)) {
      problems.push(`journey ${owner.journeyId} is not traceable to its mounted live screen`);
    }
  }
  if (requireExtensions) {
    for (const extension of plan.extensionPoints || []) {
      if (selectedJourneys && !(extension.owningJourneys || []).some((id) => selectedJourneys.has(id))) continue;
      const source = tree?.[extension.module];
      if (typeof source !== "string") { problems.push(`custom extension missing: ${extension.module}`); continue; }
      for (const name of extension.requiredExports || []) {
        if (!hasExport(source, name)) problems.push(`${extension.module} must export ${name}`);
      }
    }
  }
  return { ok: problems.length === 0, problems };
}

