// Deterministic universal scaffold composer.
//
// The composer owns mounting and common structural mechanics. Model-owned screen slots are
// created before generation and mounted immediately; the model may replace their presentation
// and connect declared capability/extension interfaces, but cannot replace the router/shell.

import { createHash } from "node:crypto";

